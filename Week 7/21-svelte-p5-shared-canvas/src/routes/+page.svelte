<h1>Week 7 — Shared canvas</h1>

<p>This project is the browser side. Start a relay from 19-express-ws-relay first, in its own terminal.</p>

<h2>1. Everyone together</h2>
<p>Uses the plain Track 1 relay, unchanged:</p>
<pre>cd 19-express-ws-relay
npm start</pre>
<p>Open <a href="/together">Everyone together</a> in two or more windows and draw.</p>

<h2>2. Rooms</h2>
<p>Stop the plain relay (Ctrl+C) and start the rooms relay:</p>
<pre>npm run rooms</pre>
<p>Open <a href="/rooms">Rooms</a>: one window creates a room, the others join it with the 4-digit code.</p>
