<h1>Week 7 — Realtime chat</h1>

<p>
	This project is the browser side. The relay (19-express-ws-relay) must be running first, in
	its own terminal:
</p>
<pre>cd 19-express-ws-relay
npm start</pre>

<p>Then open <a href="/live">the live chat</a> in two or more browser windows, side by side.</p>

<p>
	For the lab, stop the relay (Ctrl+C) and start the lab version instead with
	<code>npm run lab</code>, then open <a href="/lab">the lab page</a>.
</p>
